/**
 * Wave 18-7 / CTI-T7-008 — webhook signature verification tests.
 *
 * Pins cross-language byte-equivalence with:
 *   - Rust signer: services/api/src/routes/webhooks.rs::sign_payload
 *   - Go verifier: tools/nanorix-webhook-verify-go/verifier.go
 *   - Python verifier: sdk/python/src/nanorix/resources/webhooks.py
 *
 * If any implementation drifts on the HMAC wire form (`{ts}.{body}` +
 * `sha256=` prefix + lowercase hex), this test fails.
 *
 * Forever-Standard: wire form is permanent.
 */
import { describe, it, expect, vi, afterEach } from "vitest";
import { createHmac } from "node:crypto";
import { Webhooks } from "../src/resources/webhooks.js";

// Cross-language fixture: generated by Go signer
// (tools/nanorix-webhook-verify-go) on 2026-05-11. Pinned here so the
// TypeScript verifier MUST accept it. If TypeScript drifts, this test
// fails.
const FIXTURE_BODY = Buffer.from(
  `{"event":"capsule.created","capsule_id":"cap_123","at":"2026-05-11T00:00:00Z"}`,
);
const FIXTURE_SECRET = "whsec_fixture_pin_2026";
const FIXTURE_TIMESTAMP = 1_715_000_000;
const FIXTURE_SIGNATURE =
  "sha256=2675fe0d4fd177bc35bcaa489e35c96c8f714031e49f79004e727111ec1e7777";

function sign(body: Buffer, secret: string, timestamp: number): string {
  const mac = createHmac("sha256", secret);
  mac.update(`${timestamp}.`);
  mac.update(body);
  return `sha256=${mac.digest("hex")}`;
}

describe("Webhook signature verification (CTI-T7-008)", () => {
  afterEach(() => {
    vi.restoreAllMocks();
  });

  it("verifies the cross-language Go-generated fixture", () => {
    // Pin Date.now() to the fixture timestamp so replay protection does
    // not reject the (intentionally stable) fixture.
    vi.spyOn(Date, "now").mockReturnValue(FIXTURE_TIMESTAMP * 1000);

    expect(
      Webhooks.verifySignature(
        FIXTURE_BODY,
        FIXTURE_SIGNATURE,
        FIXTURE_SECRET,
        FIXTURE_TIMESTAMP,
      ),
    ).toBe(true);
  });

  it("TypeScript signer matches the Go fixture byte-for-byte", () => {
    const computed = sign(FIXTURE_BODY, FIXTURE_SECRET, FIXTURE_TIMESTAMP);
    expect(computed).toBe(FIXTURE_SIGNATURE);
  });

  it("round-trips a valid signature", () => {
    const body = Buffer.from('{"event":"capsule.created","capsule_id":"cap_x"}');
    const secret = "whsec_test";
    const ts = Math.floor(Date.now() / 1000);
    const sig = sign(body, secret, ts);

    expect(Webhooks.verifySignature(body, sig, secret, ts)).toBe(true);
  });

  it("rejects a tampered body", () => {
    const body = Buffer.from('{"event":"capsule.created","capsule_id":"cap_x"}');
    const secret = "whsec_test";
    const ts = Math.floor(Date.now() / 1000);
    const sig = sign(body, secret, ts);

    const tampered = Buffer.from(
      '{"event":"capsule.created","capsule_id":"cap_TAMPERED"}',
    );
    expect(Webhooks.verifySignature(tampered, sig, secret, ts)).toBe(false);
  });

  it("rejects the wrong secret", () => {
    const body = Buffer.from("{}");
    const ts = Math.floor(Date.now() / 1000);
    const sig = sign(body, "whsec_real", ts);

    expect(Webhooks.verifySignature(body, sig, "whsec_wrong", ts)).toBe(false);
  });

  it("rejects a signature without the sha256= prefix", () => {
    const body = Buffer.from("{}");
    const secret = "whsec_test";
    const ts = Math.floor(Date.now() / 1000);
    const sig = sign(body, secret, ts);
    const corrupted = sig.slice("sha256=".length);

    expect(Webhooks.verifySignature(body, corrupted, secret, ts)).toBe(false);
  });

  it("rejects a stale timestamp (> 5 minutes old)", () => {
    const body = Buffer.from("{}");
    const secret = "whsec_test";
    const staleTs = Math.floor(Date.now() / 1000) - 600;
    const sig = sign(body, secret, staleTs);

    expect(Webhooks.verifySignature(body, sig, secret, staleTs)).toBe(false);
  });

  it("rejects a future timestamp (clock-skew attack)", () => {
    const body = Buffer.from("{}");
    const secret = "whsec_test";
    const futureTs = Math.floor(Date.now() / 1000) + 600;
    const sig = sign(body, secret, futureTs);

    expect(Webhooks.verifySignature(body, sig, secret, futureTs)).toBe(false);
  });

  it("accepts a signature within the replay window", () => {
    const body = Buffer.from("{}");
    const secret = "whsec_test";
    const ts = Math.floor(Date.now() / 1000) - 60; // 1 min ago
    const sig = sign(body, secret, ts);

    expect(Webhooks.verifySignature(body, sig, secret, ts)).toBe(true);
  });

  it("accepts an empty-body signature", () => {
    const body = Buffer.alloc(0);
    const secret = "whsec_empty";
    const ts = Math.floor(Date.now() / 1000);
    const sig = sign(body, secret, ts);

    expect(Webhooks.verifySignature(body, sig, secret, ts)).toBe(true);
  });

  it("only emits lowercase hex per Forever-Standard", () => {
    const body = Buffer.from("{}");
    const secret = "whsec_test";
    const sig = sign(body, secret, 1_715_000_000);
    const hexPart = sig.slice("sha256=".length);
    expect(hexPart).toBe(hexPart.toLowerCase());
  });

  it("signatures differ across timestamps", () => {
    const body = Buffer.from("{}");
    const secret = "whsec_test";
    const a = sign(body, secret, 1_715_000_000);
    const b = sign(body, secret, 1_715_000_001);
    expect(a).not.toBe(b);
  });

  it("signatures differ across bodies", () => {
    const secret = "whsec_test";
    const ts = 1_715_000_000;
    const a = sign(Buffer.from("a"), secret, ts);
    const b = sign(Buffer.from("b"), secret, ts);
    expect(a).not.toBe(b);
  });

  it("verifies a string body identically to a Buffer body", () => {
    const text = '{"event":"capsule.created"}';
    const secret = "whsec_test";
    const ts = Math.floor(Date.now() / 1000);
    const sig = sign(Buffer.from(text), secret, ts);

    expect(Webhooks.verifySignature(text, sig, secret, ts)).toBe(true);
    expect(Webhooks.verifySignature(Buffer.from(text), sig, secret, ts)).toBe(
      true,
    );
  });
});
