def _build_wave_n_proof(
    n_receipts: int, parent_seeds: list[tuple[str, str]] | None = None
) -> dict[str, Any]:
    """Build a Wave-N AuditProof matching the Go test buildWaveNProof shape."""
    parent_seeds = parent_seeds or []
    subsystems = [
        "eee_namespace",
        "eee_tmpfs",
        "eee_memory",
        "dire_keys",
        "dire_identity",
        "fgx_forensic",
        "rzl_audit",
        "capsule_destroy",
    ]
    methods = {
        "eee_namespace": "procfs_verification",
        "eee_tmpfs": "mountinfo_verification",
        "eee_memory": "dod_5220_multipass_wipe",
        "dire_keys": "ed25519_key_destruction",
        "dire_identity": "credential_incineration",
        "fgx_forensic": "merkle_tree_verification",
        "rzl_audit": "hash_chain_validation",
        "capsule_destroy": "capsule_lifecycle_verification",
    }

    receipts: list[dict[str, object]] = []
    leaf_chain_hashes: list[str] = []
    for i in range(n_receipts):
        in_h = _sha512_hex(f"in_{i}".encode())
        out_h = _sha512_hex(f"out_{i}".encode())
        record_id = f"rec_{i:05d}"
        chain_h = compute_record_chain_hash(
            WAVE_N_CAPSULE_ID, i, record_id, in_h, out_h, GENESIS_SHA512_HEX
        )
        tag_pool = ["pa", "rcm_claim", "dicom_study", "agent_step"]
        receipts.append(
            {
                "record_index": i,
                "record_id": record_id,
                "record_input_hash": f"sha512:{in_h}",
                "record_output_hash": f"sha512:{out_h}",
                "record_chain_hash": chain_h,
                "pattern_tag": tag_pool[i % 4],
                "merkle_inclusion_proof": [],
            }
        )
        leaf_chain_hashes.append(chain_h)

    rrmr = None
    if leaf_chain_hashes:
        root = merkle_root_sha512_null_separated(leaf_chain_hashes)
        if root is not None:
            rrmr = f"sha512:{root}"

    parents: list[dict[str, object]] = []
    parent_leaves: list[str] = []
    for i, (role, org) in enumerate(parent_seeds):
        chain_h = _sha512_hex(f"parent_{i}".encode())
        sig = _sha512_hex(f"sig_{i}".encode())
        parents.append(
            {
                "parent_chain_hash": f"sha512:{chain_h}",
                "parent_key_id": f"cust-auth-{role}-{i}",
                "parent_signature": f"base64:{sig}",
                "parent_role": role,
                "parent_jurisdiction": "US",
                "parent_organization_tag": f"vendor:{org}",
            }
        )
        parent_leaves.append(f"sha512:{chain_h}")
    ppmr = None
    if parent_leaves:
        root = merkle_root_sha512_null_separated(parent_leaves)
        if root is not None:
            ppmr = f"sha512:{root}"

    chain: list[dict[str, object]] = []
    prev_hash = GENESIS_SHA512_HEX
    for i, subsystem in enumerate(subsystems):
        method = methods[subsystem]
        if i == 7:
            chain_hash = compute_step_8_amended(prev_hash, WAVE_N_TIMESTAMP, rrmr, ppmr)
        else:
            chain_hash = _compute_step_hash(
                prev_hash, subsystem, method, WAVE_N_TIMESTAMP
            )
        chain.append(
            {
                "subsystem": subsystem,
                "method": method,
                "chain_hash": chain_hash,
            }
        )
        prev_hash = chain_hash
    final_hash = chain[7]["chain_hash"]

    proof: dict[str, Any] = {
        "cdp_version": "1.0",
        "capsule_id": WAVE_N_CAPSULE_ID,
        "destroyed_at": WAVE_N_TIMESTAMP,
        "chain": chain,
        "final_hash": final_hash,
        "attestation": {
            "algorithm": "Ed25519",
            "signing_key_version": "1",
        },
    }
    if n_receipts > 0:
        proof["record_receipts"] = receipts
        if rrmr is not None:
            proof["record_receipts_merkle_root"] = rrmr
    if parent_seeds:
        proof["parent_proof_hashes"] = parents
        if ppmr is not None:
            proof["parent_proofs_merkle_root"] = ppmr
    return proof


