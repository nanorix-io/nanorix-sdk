def test_forever_standard_pre_wave_n_proof_byte_identical() -> None:
    """Pre-Wave-N proof (no receipts, no parents) MUST verify on BOTH the
    V1 verifier (verify) AND the Wave-N pipeline (verify_full_audit_proof)
    with byte-identical Step 8 chain hashes.

    Forever-Standard guarantee: pre-Wave-N AuditProofs continue to verify
    when the new code path is used to inspect them.
    """
    priv = Ed25519PrivateKey.generate()
    pub_bytes = priv.public_key().public_bytes_raw()

    methods = [
        "procfs_verification",
        "mountinfo_verification",
        "dod_5220_multipass_wipe",
        "ed25519_key_destruction",
        "credential_incineration",
        "merkle_tree_verification",
        "hash_chain_validation",
        "capsule_lifecycle_verification",
    ]
    chain = []
    prev = GENESIS_HASH
    for idx, (subsys, method) in enumerate(zip(CANONICAL_SUBSYSTEMS, methods), start=1):
        h = _compute_step_hash(prev, subsys, method, WAVE_N_TIMESTAMP)
        chain.append(
            {
                "step": idx,
                "subsystem": subsys,
                "operation": "destroy",
                "method": method,
                "timestamp": WAVE_N_TIMESTAMP,
                "evidence_hash": "sha512:" + _sha512_hex(f"step{idx}".encode()),
                "chain_hash": "sha512:" + h,
            }
        )
        prev = h
    final_chain_hash = prev
    sig = priv.sign(final_chain_hash.encode("ascii"))

    proof = {
        "cdp_version": "1.0",
        "capsule_id": WAVE_N_CAPSULE_ID,
        "destroyed_at": WAVE_N_TIMESTAMP,
        "chain": chain,
        "final_hash": "sha512:" + final_chain_hash,
        "attestation": {
            "algorithm": "Ed25519",
            "key_id": "test-key-1",
            "public_key": "base64:" + base64.b64encode(pub_bytes).decode("ascii"),
            "signature": "base64:" + base64.b64encode(sig).decode("ascii"),
        },
    }

    # V1 verifier — must accept.
    v1_result = verify(proof)
    assert v1_result.ok, f"V1 verifier must accept pre-Wave-N proof; got {v1_result}"

    # Wave-N verifier — must accept the same proof.
    wn_result = verify_full_audit_proof(proof)
    assert wn_result.valid, (
        f"Wave-N verifier must accept pre-Wave-N proof; got {wn_result}"
    )

    # Step 8 chain hash in (None, None) arm MUST equal pre-Wave-N legacy formula.
    step7_hash = str(chain[6]["chain_hash"]).removeprefix("sha512:")
    step8_hash = str(chain[7]["chain_hash"]).removeprefix("sha512:")
    step_8_amended = compute_step_8_amended(step7_hash, WAVE_N_TIMESTAMP, None, None)
    assert step_8_amended == step8_hash, (
        "Forever-Standard violation: Step 8 (None, None) MUST equal legacy"
    )


